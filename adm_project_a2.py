non_merchandise_codes = {
    "M", "m",                 # Manual entries
    "DOT", "POST", "C2",       # Delivery and carriage
    "AMAZONFEE", "BANK CHARGES",
    "B",                      # Bad-debt adjustment
    "ADJUST", "ADJUST2",       # Adjustments
    "D",                      # Discount entries
    "TEST001",                # Test entry
    "S",                      # Samples
}

