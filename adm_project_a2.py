"""## 4. Customer Feature Engineering

Customer behaviour is summarised using RFM:

- Recency: days since the customer's latest eligible purchase.
- Frequency: number of distinct eligible purchase invoices.
- Monetary: total eligible purchase value.

Fees, adjustments, vouchers, samples, and test entries are excluded.
The purchase on invoice 581483 is excluded because the original data
shows an exact full reversal shortly afterwards.

Monetary value measures purchase spending after these exclusions.
It is not fully reconciled net spending: other returns have not been
systematically matched to their original purchases.

Create the eligible merchandise dataset
"""

