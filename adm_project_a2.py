cleaning_log = []

def record_step(step, before, after):
    cleaning_log.append({
        "step": step,
        "rows_removed": before - after,
        "rows_remaining": after,
    })

record_step("Starting dataset", len(working_df), len(working_df))

# Exclude source_sheet when checking duplicate transactions.
transaction_columns = [
    column for column in working_df.columns
    if column != "source_sheet"
]

before = len(working_df)
working_df = working_df.drop_duplicates(
    subset=transaction_columns
).copy()
record_step("Remove exact duplicates", before, len(working_df))

# Apply filters sequentially so removed counts do not overlap.
filters = [
    (
        "Remove missing invoice, stock code, or date",
        lambda data: data[
            ["invoice", "stock_code", "invoice_date"]
        ].notna().all(axis=1),
    ),
    (
        "Remove cancellation invoices",
        lambda data: ~data["invoice"].str.upper().str.startswith(
            "C", na=False
        ),
    ),
    (
        "Keep positive quantities",
        lambda data: data["quantity"].gt(0),
    ),
    (
        "Keep positive unit prices",
        lambda data: data["unit_price"].gt(0),
    ),
]

